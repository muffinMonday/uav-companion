// Builds src/data/china-outline.js: a small outline of China (mainland, Hong Kong, Macao; not Taiwan) from Natural Earth (public domain).
// The app uses it only to decide whether a place is in China (Amap first) or not (Google Maps only), so a coarse outline is enough.
//   node scripts/make-china-outline.js            downloads Natural Earth 1:50m countries and writes the file
//   node scripts/make-china-outline.js file.json  uses a copy you already have
import fs from 'node:fs';

const URL_NE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson';
const KEEP = new Set(['CHN', 'HKG', 'MAC']);
const TOLERANCE = 0.03; // degrees, about 3 km
const MIN_AREA = 0.002; // square degrees: tiny islands are left out (Hong Kong and Macao are kept)

const src = process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8') : await (await fetch(URL_NE)).text();
const gj = JSON.parse(src);

// Douglas-Peucker on a ring of [lon, lat]
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Array(pts.length).fill(false);
  keep[0] = keep[pts.length - 1] = true;
  const dist = (p, a, b) => {
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const t = dx || dy ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy))) : 0;
    return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
  };
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop();
    let max = 0, at = -1;
    for (let k = i + 1; k < j; k++) { const d = dist(pts[k], pts[i], pts[j]); if (d > max) { max = d; at = k; } }
    if (max > tol) { keep[at] = true; stack.push([i, at], [at, j]); }
  }
  return pts.filter((_, k) => keep[k]);
}
const area = (ring) => Math.abs(ring.reduce((s, p, i) => { const q = ring[(i + 1) % ring.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0) / 2);

const rings = [];
for (const f of gj.features) {
  if (!KEEP.has(f.properties.ADM0_A3)) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    const outer = poly[0];
    if (area(outer) < MIN_AREA) continue;
    const r = simplify(outer, Math.min(TOLERANCE, Math.sqrt(area(outer)) / 8)).map(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100]);
    if (r.length >= 4) rings.push(r);
  }
}
// The 1:50m outlines of Hong Kong and Macao have gaps (Kowloon, the Macao peninsula), so both are covered by a slightly generous box.
rings.push([[113.83, 22.15], [114.45, 22.15], [114.45, 22.57], [113.83, 22.57], [113.83, 22.15]]);
rings.push([[113.52, 22.10], [113.61, 22.10], [113.61, 22.23], [113.52, 22.23], [113.52, 22.10]]);
fs.mkdirSync('src/data', { recursive: true });
const data = { source: 'Natural Earth 1:50m admin 0 countries (public domain): China, Hong Kong, Macao; simplified', rings };
fs.writeFileSync('src/data/china-outline.js', `// Generated by scripts/make-china-outline.js. Do not edit.
export default ${JSON.stringify(data)};
`);
console.log(`${rings.length} rings, ${rings.reduce((s, r) => s + r.length, 0)} points`);
